SELECT
    PROMOTION_ID,
    PROMOTION_NAME,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(DISCOUNT_AMOUNT) AS TOTAL_DISCOUNT_AMOUNT,
    SUM(GROSS_AMOUNT) AS TOTAL_GROSS_SALES,
    SUM(NET_SALES_AMOUNT) AS TOTAL_NET_SALES
FROM {{ ref('int_sales_enriched') }}
GROUP BY
    PROMOTION_ID,
    PROMOTION_NAME