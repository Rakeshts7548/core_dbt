SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    PRODUCT_ID,
    PRODUCT_NAME,
    COUNT(*) AS TOTAL_PURCHASES,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(NET_SALES_AMOUNT) AS TOTAL_REVENUE
FROM {{ ref('int_sales_enriched') }}
GROUP BY
    CUSTOMER_ID,
    CUSTOMER_NAME,
    PRODUCT_ID,
    PRODUCT_NAME